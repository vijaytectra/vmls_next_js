// Reads the real pixel size of every image used as an og:image and writes
// them to src/data/og-image-sizes.ts, so og:image:width / og:image:height
// describe the actual file instead of an assumed 1200x630.
//
// Re-run when og images change:  node scripts/generate-og-image-sizes.mjs
import fs from "node:fs";

const OUT = "src/data/og-image-sizes.ts";

function dimensions(buf) {
  if (buf.slice(0, 8).toString("hex") === "89504e470d0a1a0a")
    return [buf.readUInt32BE(16), buf.readUInt32BE(20)];
  if (buf.slice(0, 4).toString() === "RIFF" && buf.slice(8, 12).toString() === "WEBP") {
    const fmt = buf.slice(12, 16).toString();
    if (fmt === "VP8 ")
      return [buf.readUInt16LE(26) & 0x3fff, buf.readUInt16LE(28) & 0x3fff];
    if (fmt === "VP8L") {
      const b = buf.readUInt32LE(21);
      return [(b & 0x3fff) + 1, ((b >> 14) & 0x3fff) + 1];
    }
    if (fmt === "VP8X")
      return [
        1 + (buf.readUIntLE(24, 3) & 0xffffff),
        1 + (buf.readUIntLE(27, 3) & 0xffffff),
      ];
  }
  if (buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i < buf.length) {
      if (buf[i] !== 0xff) { i++; continue; }
      const marker = buf[i + 1];
      const len = buf.readUInt16BE(i + 2);
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker))
        return [buf.readUInt16BE(i + 7), buf.readUInt16BE(i + 5)];
      i += 2 + len;
    }
  }
  return null;
}

const sources = [
  "src/lib/seo-pages.ts",
  "src/app/faculty/[slug]/page.tsx",
  "src/data/blog-seo.ts",
];

const referenced = new Set();
for (const file of sources) {
  const src = fs.readFileSync(file, "utf8");
  for (const m of src.matchAll(/"(\/images\/[^"]+\.(?:webp|png|jpe?g|JPEG|JPG))"/g))
    referenced.add(m[1]);
}

const sizes = {};
const problems = [];
for (const img of [...referenced].sort()) {
  const file = `public${img}`;
  if (!fs.existsSync(file)) {
    problems.push(`missing file: ${img}`);
    continue;
  }
  const dim = dimensions(fs.readFileSync(file));
  if (!dim) {
    problems.push(`unreadable header: ${img}`);
    continue;
  }
  sizes[img] = dim;
}

fs.writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/generate-og-image-sizes.mjs - do not edit.\n` +
    `// Real pixel dimensions of every image used as an og:image.\n` +
    `export const OG_IMAGE_SIZES: Record<string, [number, number]> = ${JSON.stringify(
      sizes,
      null,
      2
    )};\n`
);

console.log(`wrote ${OUT}: ${Object.keys(sizes).length} images`);
problems.forEach((p) => console.log(`  ! ${p}`));
