// Writes public/.htaccess for the cPanel deployment.
//
// A static export drops two Next features, so Apache has to do that work:
//   * next.config redirects()  -> the 301 rules below
//   * src/middleware.ts        -> the three legacy newsletter PDF paths
// Both are generated from the same sources, so nothing is retyped by hand.
//
// Also handles what a Next export needs from a plain web server:
// extensionless URLs (about-vmls -> about-vmls.html), a 404 document, and
// long-lived caching for the fingerprinted /_next/static assets.
//
// Run:  node scripts/generate-htaccess.mjs
import fs from "node:fs";

const OUT = "public/.htaccess";

// Top-level directories in public_html that are NOT part of this site - separate
// apps that share the document root. Every rule below is skipped for them, so
// their own routing (and their own .htaccess) is left completely alone.
// Add a folder here before uploading if a new sibling app appears.
const SIBLING_APPS = [
  "exam",
  "vlat",
  "vlat-exam",
  "vlat-exam21",
  "wordpress blogs dont touch this",
];

/* ------------------------------------------------------------- redirects */

/** Pull the array literal out of one of the generated redirect modules. */
const readRedirects = (file, name) => {
  const src = fs.readFileSync(file, "utf8");
  return JSON.parse(src.slice(src.indexOf("= [", src.indexOf(name)) + 2, src.lastIndexOf("]") + 1));
};

// redirects.ts is rebuilt by generate-redirects.mjs, which needs a crawl of the
// old site that is not in the repo. So read the hand-maintained file directly
// too, rather than leaving new rules stranded until someone can run that.
// Manual entries come first and win: a later duplicate source is dropped.
const seenSource = new Set();
const rules = [
  ...readRedirects("src/data/redirects.manual.ts", "MANUAL_REDIRECTS"),
  ...readRedirects("src/data/redirects.ts", "export const REDIRECTS"),
].filter((r) => !seenSource.has(r.source) && seenSource.add(r.source));

// The middleware's rules, kept in the parked file so they stay in one place.
const legacySrc = fs.readFileSync("scripts/legacy-asset-redirects.ts.bak", "utf8");
const legacy = [
  ...legacySrc.matchAll(/"([^"]+\.pdf)":\s*\n?\s*"([^"]+)"/g),
].map((m) => ({ source: m[1], destination: m[2], permanent: true }));

/** Escape a literal path for use as a RewriteRule regex. */
const escapeRe = (p) => p.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/**
 * Apache per-directory rules match without the leading slash, against the
 * DECODED path - so a source holding %20 needs a rule with a real space.
 * Both forms are emitted, since the encoded one is what the old site linked.
 */
const toRules = ({ source, destination, permanent }) => {
  const flags = permanent === false ? "R=302,L,NE" : "R=301,L,NE";
  const bare = source.replace(/^\//, "");
  const forms = new Set([bare]);
  if (/%[0-9A-Fa-f]{2}/.test(bare)) {
    try {
      forms.add(decodeURIComponent(bare));
    } catch {
      /* leave the encoded form alone if it will not decode */
    }
  }
  // Quote both sides: several legacy filenames contain spaces.
  return [...forms].map(
    (form) => `RewriteRule "^${escapeRe(form)}$" "${destination}" [${flags}]`
  );
};

const all = [...rules, ...legacy];

// A destination that is also a source would bounce the visitor twice.
const sources = new Set(all.map((r) => r.source));
const chains = all.filter((r) => sources.has(r.destination));

/* ----------------------------------------------------------------- file */

const header = `# AUTO-GENERATED by scripts/generate-htaccess.mjs - do not edit by hand.
# Regenerate after changing src/data/redirects.ts, then re-upload.
#
# Serves the Next.js static export (./out) from Apache on cPanel.

Options -Indexes

# mod_dir is what breaks a Next export on Apache. /about-vmls maps to the
# about-vmls/ directory of RSC payloads, so DirectorySlash 301s it to
# /about-vmls/, which holds no index.html - and no rewrite ordering trick
# reliably beats it. Turning it off removes the redirect entirely, leaving the
# rewrite below free to serve about-vmls.html.
#
# This applies to the whole document root, so the sibling apps lose the slash
# redirect they rely on. The first RewriteRule below hands it back to them.
DirectorySlash Off

# index.php is listed because this .htaccess sits at the document root and is
# therefore inherited by the sibling apps that share public_html (/exam, /vlat).
# Those are PHP; without index.php here their directory URLs stop resolving.
DirectoryIndex index.html index.php

<IfModule mod_rewrite.c>
  RewriteEngine On

  # ---------------------------------------------------------------------
  # Hand the sibling apps straight back to Apache before any rule below can
  # rewrite them. Without this, the trailing-slash rule would 301 their
  # virtual routes (/exam/results/ -> /exam/results) and break them.
  # ---------------------------------------------------------------------
  # Restore the trailing slash that DirectorySlash Off took away, so /exam
  # still reaches /exam/ and its DirectoryIndex. This must come first: the
  # bypass rule below would otherwise end processing before it runs.
  RewriteRule "^(${SIBLING_APPS.join("|")})$" "/$1/" [R=301,L]

  RewriteRule "^(${SIBLING_APPS.join("|")})(/|$)" - [L]

  # ---------------------------------------------------------------------
  # Canonical host. Left commented out deliberately: switching these on
  # changes which hostname the site answers on, so enable them only when
  # the DNS and SSL for that host are confirmed.
  # ---------------------------------------------------------------------
  # RewriteCond %{HTTPS} off
  # RewriteRule ^(.*)$ https://vmls.edu.in/$1 [R=301,L]
  # RewriteCond %{HTTP_HOST} ^www\\.vmls\\.edu\\.in$ [NC]
  # RewriteRule ^(.*)$ https://vmls.edu.in/$1 [R=301,L]

  # ---------------------------------------------------------------------
  # 301s from the previous static site. ${all.length} rules.
  # These must stay ABOVE the extensionless-URL rewrite below.
  # ---------------------------------------------------------------------
`;

const footer = `
  # ---------------------------------------------------------------------
  # Next.js static export: serve /about-vmls from about-vmls.html without
  # showing the extension, and send /about-vmls/ to the clean URL so the
  # two forms do not both resolve.
  #
  # Neither rule may test !-d. The export writes about-vmls.html AND an
  # about-vmls/ directory of RSC payloads, so a !-d test skips exactly the
  # paths that need rewriting - mod_dir then 301s /about-vmls to
  # /about-vmls/, finds no index.html there, and serves 403.
  #
  # "does $1.html exist" is the correct guard instead, and it has to appear on
  # the trailing-slash rule too: without it /images/ would be redirected to
  # /images, which mod_dir would send straight back to /images/, forever.
  #
  # mod_rewrite runs before mod_dir, so the internal rewrite below wins and
  # mod_dir never sees a directory to redirect to.
  # ---------------------------------------------------------------------
  RewriteBase /

  RewriteCond %{REQUEST_URI} !^/_next/
  RewriteCond %{DOCUMENT_ROOT}/$1.html -f
  RewriteRule ^(.+)/$ /$1 [R=301,L]

  # The substitution below is RELATIVE on purpose. In per-directory context a
  # substitution beginning with "/" is taken as a filesystem path, so "/$1.html"
  # looked for /about-vmls.html at the server root, found nothing, and left the
  # request pointing at the about-vmls/ directory - which mod_dir then 301'd to
  # about-vmls/, straight into a loop with the rule above.
  # [END], not [L]. [L] ends only this round: Apache then re-runs the whole
  # file against the rewritten URI, where "library.html -> /library" above
  # fires and 301s back to /library, forever. That loop hits exactly the pages
  # whose legacy rule shares their name - library, blogs, student-affairs -
  # and leaves ones like about.html -> /about-vmls working, which is what made
  # it look like a partial failure. [END] stops per-directory reprocessing
  # outright, so the legacy rules only ever see the original request.
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{DOCUMENT_ROOT}/$1.html -f
  RewriteRule ^(.+?)/?$ $1.html [END]
</IfModule>

ErrorDocument 404 /404.html

# Fingerprinted build assets never change under the same name.
<IfModule mod_expires.c>
  ExpiresActive On
  # mp4/webm/pdf were missing, so the 12 MB hero video shipped with no cache
  # headers at all - the largest single item in PageSpeed's "efficient cache
  # lifetimes" report.
  <FilesMatch "\\.(js|css|woff2|woff|ttf|webp|png|jpe?g|gif|svg|ico|mp4|webm|pdf)$">
    ExpiresDefault "access plus 1 year"
  </FilesMatch>
  <FilesMatch "\\.(html|xml|txt)$">
    ExpiresDefault "access plus 1 hour"
  </FilesMatch>
</IfModule>

<IfModule mod_headers.c>
  # FilesMatch tests the FILE NAME, never a path, so "^/_next/static/" matched
  # nothing at all. Static assets here are content-hashed or versioned, so
  # match them by extension instead.
  <FilesMatch "\\.(js|css|woff2|woff|ttf|webp|png|jpe?g|gif|svg|ico|mp4|webm)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml
</IfModule>
`;

fs.writeFileSync(
  OUT,
  header + all.flatMap((r) => toRules(r).map((rule) => `  ${rule}`)).join("\n") + "\n" + footer
);

console.log(`wrote ${OUT}: ${all.length} redirect rules (${rules.length} from the map, ${legacy.length} legacy assets)`);
if (chains.length) {
  console.log(`\nWARNING - ${chains.length} rule(s) point at a URL that is itself redirected:`);
  chains.forEach((c) => console.log(`  ${c.source} -> ${c.destination}`));
}
