// Writes public/.htaccess for the cPanel deployment.
//
// A static export drops two Next features, so Apache has to do that work:
//   * next.config redirects()  -> the 301 rules below
//   * src/middleware.ts        -> the three legacy newsletter PDF paths
// Both are generated from the same sources, so nothing is retyped by hand.
//
// Also handles what a Next export needs from a plain web server:
// extensionless URLs (about-vmls -> about-vmls.html), a 404 document, and
// long-lived caching for the fingerprinted /_next/static assets.
//
// Run:  node scripts/generate-htaccess.mjs
import fs from "node:fs";

const OUT = "public/.htaccess";

/* ------------------------------------------------------------- redirects */

const redirectsSrc = fs.readFileSync("src/data/redirects.ts", "utf8");
const rules = JSON.parse(
  redirectsSrc.slice(
    redirectsSrc.indexOf("= [", redirectsSrc.indexOf("export const REDIRECTS")) + 2,
    redirectsSrc.lastIndexOf("]") + 1
  )
);

// The middleware's rules, kept in the parked file so they stay in one place.
const legacySrc = fs.readFileSync("scripts/legacy-asset-redirects.ts.bak", "utf8");
const legacy = [
  ...legacySrc.matchAll(/"([^"]+\.pdf)":\s*\n?\s*"([^"]+)"/g),
].map((m) => ({ source: m[1], destination: m[2], permanent: true }));

/** Escape a literal path for use as a RewriteRule regex. */
const escapeRe = (p) => p.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/**
 * Apache per-directory rules match without the leading slash, against the
 * DECODED path - so a source holding %20 needs a rule with a real space.
 * Both forms are emitted, since the encoded one is what the old site linked.
 */
const toRules = ({ source, destination, permanent }) => {
  const flags = permanent === false ? "R=302,L,NE" : "R=301,L,NE";
  const bare = source.replace(/^\//, "");
  const forms = new Set([bare]);
  if (/%[0-9A-Fa-f]{2}/.test(bare)) {
    try {
      forms.add(decodeURIComponent(bare));
    } catch {
      /* leave the encoded form alone if it will not decode */
    }
  }
  // Quote both sides: several legacy filenames contain spaces.
  return [...forms].map(
    (form) => `RewriteRule "^${escapeRe(form)}$" "${destination}" [${flags}]`
  );
};

const all = [...rules, ...legacy];

// A destination that is also a source would bounce the visitor twice.
const sources = new Set(all.map((r) => r.source));
const chains = all.filter((r) => sources.has(r.destination));

/* ----------------------------------------------------------------- file */

const header = `# AUTO-GENERATED by scripts/generate-htaccess.mjs - do not edit by hand.
# Regenerate after changing src/data/redirects.ts, then re-upload.
#
# Serves the Next.js static export (./out) from Apache on cPanel.

Options -Indexes
DirectoryIndex index.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # ---------------------------------------------------------------------
  # Canonical host. Left commented out deliberately: switching these on
  # changes which hostname the site answers on, so enable them only when
  # the DNS and SSL for that host are confirmed.
  # ---------------------------------------------------------------------
  # RewriteCond %{HTTPS} off
  # RewriteRule ^(.*)$ https://vmls.edu.in/$1 [R=301,L]
  # RewriteCond %{HTTP_HOST} ^www\\.vmls\\.edu\\.in$ [NC]
  # RewriteRule ^(.*)$ https://vmls.edu.in/$1 [R=301,L]

  # ---------------------------------------------------------------------
  # 301s from the previous static site. ${all.length} rules.
  # These must stay ABOVE the extensionless-URL rewrite below.
  # ---------------------------------------------------------------------
`;

const footer = `
  # ---------------------------------------------------------------------
  # Next.js static export: serve /about-vmls from about-vmls.html without
  # showing the extension, and send /about-vmls/ to the clean URL so the
  # two forms do not both resolve.
  # ---------------------------------------------------------------------
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteCond %{REQUEST_URI} !^/_next/
  RewriteRule ^(.+)/$ /$1 [R=301,L]

  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteCond %{DOCUMENT_ROOT}/$1.html -f
  RewriteRule ^(.+?)/?$ /$1.html [L]
</IfModule>

ErrorDocument 404 /404.html

# Fingerprinted build assets never change under the same name.
<IfModule mod_expires.c>
  ExpiresActive On
  <FilesMatch "\\.(js|css|woff2|webp|png|jpe?g|svg|ico)$">
    ExpiresDefault "access plus 1 year"
  </FilesMatch>
  <FilesMatch "\\.(html|xml|txt)$">
    ExpiresDefault "access plus 1 hour"
  </FilesMatch>
</IfModule>

<IfModule mod_headers.c>
  <FilesMatch "^/_next/static/">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml
</IfModule>
`;

fs.writeFileSync(
  OUT,
  header + all.flatMap((r) => toRules(r).map((rule) => `  ${rule}`)).join("\n") + "\n" + footer
);

console.log(`wrote ${OUT}: ${all.length} redirect rules (${rules.length} from the map, ${legacy.length} legacy assets)`);
if (chains.length) {
  console.log(`\nWARNING - ${chains.length} rule(s) point at a URL that is itself redirected:`);
  chains.forEach((c) => console.log(`  ${c.source} -> ${c.destination}`));
}
