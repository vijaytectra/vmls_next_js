// The faculty list lives inside src/app/faculty/[slug]/page.tsx. The sitemap
// needs the slugs without importing a page component, so they are mirrored
// into a plain data module here.
//
// Re-run after adding or removing faculty:
//   node scripts/generate-faculty-slugs.mjs
import fs from "node:fs";

const SRC = "src/app/faculty/[slug]/page.tsx";
const OUT = "src/data/faculty-slugs.ts";

const src = fs.readFileSync(SRC, "utf8");
const slugs = [...src.matchAll(/^    slug: "([^"]+)",$/gm)].map((m) => m[1]);
if (!slugs.length) throw new Error("no faculty slugs parsed from " + SRC);

fs.writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/generate-faculty-slugs.mjs - do not edit by hand.\n` +
    `// Source of truth: ${SRC}\n` +
    `export const facultySlugs: string[] = ${JSON.stringify(slugs, null, 2)};\n`
);
console.log(`wrote ${OUT}: ${slugs.length} faculty slugs`);
