// Generates per-post SEO fields from src/data/blogs/content.json, which is
// the source of truth for article content after the blog refactor.
// The article page is a client component, so its metadata and JSON-LD are
// declared in src/app/blogs/[slug]/layout.tsx from this module.
//
// Re-run after adding or editing posts:  node scripts/generate-blog-seo.mjs
import fs from "node:fs";

const SRC = "src/data/blogs/content.json";
const OUT = "src/data/blog-seo.ts";

const posts = JSON.parse(fs.readFileSync(SRC, "utf8"));

const decode = (s) =>
  String(s)
    .split("&apos;").join("’")
    .split("&#39;").join("’")
    .split("&quot;").join('"')
    .split("&amp;").join("&")
    .split("&nbsp;").join(" ")
    .replace(/\s+/g, " ")
    .trim();

const stripTags = (html) => decode(String(html).replace(/<[^>]*>/g, " "));

// Trim to the 150-160 band, preferring a word boundary but never landing short.
const clamp = (text, max = 158) => {
  const t = decode(text);
  if (t.length <= max) return t;
  const at = t.slice(0, max).lastIndexOf(" ");
  const onWord = at > 0 ? t.slice(0, at).replace(/[,;:.\s]+$/, "") : "";
  const bodyText = onWord.length >= 149 ? onWord : t.slice(0, max - 1).trimEnd();
  return `${bodyText}…`;
};

const seo = {};
let withFaqs = 0;

for (const [slug, post] of Object.entries(posts)) {
  // Take whole paragraphs in order until there is enough for a description.
  const paras = [...String(post.html ?? "").matchAll(/<p[^>]*>([\s\S]*?)<\/p>/g)]
    .map((m) => stripTags(m[1]))
    .filter(Boolean);
  let prose = "";
  for (const para of paras) {
    prose = prose ? `${prose} ${para}` : para;
    if (prose.length >= 150) break;
  }

  // Only FAQs the article actually renders (BlogArticleContent shows them).
  const faqs = Array.isArray(post.faqs)
    ? post.faqs
        .map((f) => ({ q: decode(f.question), a: stripTags(f.answerHtml) }))
        .filter((f) => f.q && f.a)
    : [];
  if (faqs.length) withFaqs++;

  seo[slug] = {
    slug,
    title: decode(post.title ?? slug),
    author: decode(post.author ?? ""),
    date: post.date ?? "",
    image: post.image ?? "",
    description: clamp(prose || decode(post.title ?? "")),
    ...(faqs.length ? { faqs } : {}),
  };
}

const out = `// AUTO-GENERATED by scripts/generate-blog-seo.mjs - do not edit by hand.
// Source of truth: src/data/blogs/content.json.
export type BlogFaqSeo = { q: string; a: string };

export type BlogSeo = {
  slug: string;
  title: string;
  author: string;
  date: string;
  image: string;
  description: string;
  /** Present only when the article renders these Q&As visibly. */
  faqs?: BlogFaqSeo[];
};

export const BLOG_SEO: Record<string, BlogSeo> = ${JSON.stringify(seo, null, 2)};

export const BLOG_SLUGS = Object.keys(BLOG_SEO);
`;

fs.writeFileSync(OUT, out);
console.log(
  `wrote ${OUT}: ${Object.keys(seo).length} posts, ${withFaqs} with visible FAQs`
);
