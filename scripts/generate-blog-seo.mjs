// One-off generator: extracts SEO fields for each blog post from the
// blogData map inside src/app/blogs/[slug]/page.tsx (a client component,
// so a server-side generateMetadata cannot import it directly).
// Re-run after adding a post:  node scripts/generate-blog-seo.mjs
import fs from "node:fs";

const SRC = "src/app/blogs/[slug]/page.tsx";
const OUT = "src/data/blog-seo.ts";

const file = fs.readFileSync(SRC, "utf8").split("\r\n").join("\n");
const start = file.indexOf("const blogData = {");
if (start === -1) throw new Error("blogData map not found in " + SRC);
const body = file.slice(start);

const decode = (s) =>
  s
    .split("&apos;").join("’")
    .split("&quot;").join('"')
    .split("&amp;").join("&")
    .split("&nbsp;").join(" ")
    .replace(/\s+/g, " ")
    .trim();

// Trim to <=160 chars on a word boundary, aiming for the 150-160 band.
const clamp = (text, max = 158) => {
  const t = decode(text);
  if (t.length <= max) return t;
  const at = t.slice(0, max).lastIndexOf(" ");
  const onWord = at > 0 ? t.slice(0, at).replace(/[,;:.\s]+$/, "") : "";
  // Keep the result inside the 150-160 band: a word boundary that lands
  // short of 150 is worse than one character of a cut word.
  const body = onWord.length >= 149 ? onWord : t.slice(0, max - 1).trimEnd();
  return `${body}…`;
};

const entries = [];
const keys = [...body.matchAll(/^  "([A-Za-z0-9-]+)":\s*\{$/gm)];
for (let i = 0; i < keys.length; i++) {
  const slug = keys[i][1];
  const from = keys[i].index + keys[i][0].length;
  const to = i + 1 < keys.length ? keys[i + 1].index : body.length;
  const block = body.slice(from, to);
  const field = (n) => (block.match(new RegExp(n + ':\\s*"([^"]*)"')) || [])[1] || "";
  // Take whole paragraphs in order until there is enough text for a
  // 150-160 character description.
  const paras = [...block.matchAll(/<p[^>]*>([\s\S]*?)<\/p>/g)].map((m) =>
    m[1].replace(/<[^>]*>/g, " ")
  );
  let prose = "";
  for (const para of paras) {
    prose = prose ? `${prose} ${para}` : para;
    if (decode(prose).length >= 150) break;
  }
  entries.push({
    slug,
    title: decode(field("title")),
    author: decode(field("author")),
    date: field("date"),
    image: field("image"),
    description: clamp(prose),
  });
}
if (!entries.length) throw new Error("no blog entries parsed");

const out = `// AUTO-GENERATED by scripts/generate-blog-seo.mjs - do not edit by hand.
// Source of truth: src/app/blogs/[slug]/page.tsx (blogData).
export type BlogSeo = {
  slug: string;
  title: string;
  author: string;
  date: string;
  image: string;
  description: string;
};

export const BLOG_SEO: Record<string, BlogSeo> = ${JSON.stringify(
  Object.fromEntries(entries.map((e) => [e.slug, e])),
  null,
  2
)};

export const BLOG_SLUGS = Object.keys(BLOG_SEO);
`;
fs.writeFileSync(OUT, out);
console.log("wrote " + OUT + ": " + entries.length + " posts");
