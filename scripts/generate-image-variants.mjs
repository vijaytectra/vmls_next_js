// Pre-generates responsive width variants for every image the site uses, and
// writes a manifest the custom loader reads.
//
// Why: this app is a static export with no image server, and it was running
// `images.unoptimized` with a no-op loader - so every device downloaded every
// image at full resolution and no srcset was emitted anywhere. On a simulated
// 4G connection the homepage's ~1.1 MB of images alone pushed LCP past five
// seconds.
//
// Variants live beside the original as <name>-w<width>.webp. Originals are
// left untouched and remain the fallback.
//
//   node scripts/generate-image-variants.mjs [--dry]
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = "public/images";
const MANIFEST = "src/data/image-variants.ts";
const DRY = process.argv.includes("--dry");

// Matches the device / image widths Next requests, trimmed to what this
// design actually uses. 128–192 cover header and mentorship logos; 700 is a
// mid-size step for content images displayed around 600–650 CSS px.
const WIDTHS = [128, 160, 192, 256, 384, 640, 700, 828, 1200, 1920];
// Below this an image is already small enough that a variant saves nothing.
// Kept under the smallest mentorship logo (~133–268 px) so those still get
// retina-friendly smaller variants when the source is larger than 128.
const MIN_SOURCE_WIDTH = 160;
const IS_IMAGE = /\.(webp|png|jpe?g)$/i;
const IS_VARIANT = /-w\d+\.webp$/i;

const files = [];
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (IS_IMAGE.test(entry.name) && !IS_VARIANT.test(entry.name)) files.push(full);
  }
};
walk(ROOT);

// Also cover the hero poster, which lives under public/videos.
if (fs.existsSync("public/videos")) {
  for (const entry of fs.readdirSync("public/videos")) {
    if (IS_IMAGE.test(entry) && !IS_VARIANT.test(entry))
      files.push(path.join("public/videos", entry));
  }
}

const manifest = {};
let generated = 0;
let skipped = 0;
let bytesAdded = 0;

for (const file of files) {
  let meta;
  try {
    meta = await sharp(file).metadata();
  } catch {
    continue; // unreadable or not an image sharp understands
  }
  const sourceWidth = meta.width ?? 0;
  if (sourceWidth < MIN_SOURCE_WIDTH) {
    skipped++;
    continue;
  }

  const publicPath = "/" + path.relative("public", file).split(path.sep).join("/");
  const targets = WIDTHS.filter((w) => w < sourceWidth);
  if (!targets.length) {
    skipped++;
    continue;
  }

  const available = [];
  for (const width of targets) {
    const out = file.replace(IS_IMAGE, `-w${width}.webp`);
    available.push(width);
    if (DRY) continue;
    if (fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(file).mtimeMs) {
      continue; // already current
    }
    // Small widths are mostly logos/UI marks: slightly higher quality keeps
    // edges sharp at Retina without meaningful byte growth. Larger photo
    // variants stay at 75.
    const quality = width <= 256 ? 82 : 75;
    await sharp(file)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality, effort: 6, smartSubsample: true })
      .toFile(out);
    // Skip writing a variant that is larger than the original — that can
    // happen near the source width when quality is raised for small logos.
    if (fs.statSync(out).size >= fs.statSync(file).size) {
      fs.unlinkSync(out);
      available.pop();
      continue;
    }
    bytesAdded += fs.statSync(out).size;
    generated++;
  }
  // The original is the last resort for widths above every variant.
  manifest[publicPath] = [...available, sourceWidth].sort((a, b) => a - b);
}

if (!DRY) {
  fs.writeFileSync(
    MANIFEST,
    `// AUTO-GENERATED by scripts/generate-image-variants.mjs - do not edit.\n` +
      `// Maps each image to the widths that exist on disk. The custom loader in\n` +
      `// src/lib/imageLoader.ts uses this to build a real srcset without an\n` +
      `// image server.\n` +
      `export const IMAGE_VARIANTS: Record<string, number[]> = ${JSON.stringify(manifest, null, 0)};\n`
  );
}

console.log(
  `${DRY ? "DRY RUN - " : ""}${Object.keys(manifest).length} images with variants, ` +
    `${generated} files generated (${(bytesAdded / 1048576).toFixed(1)} MB), ${skipped} already small enough`
);
